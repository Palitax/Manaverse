import { CardLanguage } from "@/types";

export interface TcgSet {
  id: string;
  code: string; // e.g. "SV1S", "JTG", "SV2a", "MEW", "OBF", "PRE", "SV8a", "S6a"
  name: string;
  nameOriginal?: string;
  language: CardLanguage;
  series: string;
  releaseYear: number;
  totalCards: number;
  equivalentCode?: string; // Cross-link to counterpart (e.g. MEW <-> SV2a, SVI <-> SV1S/SV1V)
  equivalentName?: string;
  aliases: string[];
}

export interface TcgCard {
  id: string;
  name: string; // Primary clean name
  nameOriginal: string; // Original Kana / Hangul / Hanzi / German
  nameEn: string; // English standard
  nameDe: string; // German standard
  pokemon: string; // Base creature
  setCode: string; // Standard short code
  setName: string;
  number: string; // e.g. "199/165", "201/165", "215/203"
  language: CardLanguage;
  rarity: string;
  imageUrl: string;
}

