/**
 * Searches the TCG Index by query string, language filter, or set code
 */
export function searchTcgCards(
  query: string,
  languageFilter?: CardLanguage | "ALL",
  setCodeFilter?: string
): TcgCard[] {
  let list = TCG_CARDS;

  if (languageFilter && languageFilter !== "ALL") {
    list = list.filter((c) => c.language === languageFilter);
  }

  if (setCodeFilter) {
    const normSet = setCodeFilter.trim().toLowerCase();
    list = list.filter(
      (c) =>
        c.setCode.toLowerCase() === normSet ||
        c.setName.toLowerCase().includes(normSet)
    );
  }

  if (!query || query.trim().length === 0) {
    return list;
  }

  const q = query.trim().toLowerCase();
  const words = q.split(/\s+/).filter(Boolean);

  return list.filter((c) => {
    const searchable = [
      c.name,
      c.nameOriginal,
      c.nameEn,
      c.nameDe,
      c.pokemon,
      c.setCode,
      c.setName,
      c.number,
      `${c.name} ${c.setName}`,
      `${c.nameDe} ${c.setName}`,
      `${c.nameEn} ${c.setName}`,
      `${c.pokemon} ${c.setCode}`,
      `${c.pokemon} ${c.setName}`,
    ]
      .join(" ")
      .toLowerCase();

    // All words in query must match
    return words.every((w) => searchable.includes(w));
  });
}

/**
 * Returns all TCG sets filtered by language
 */
export function getTcgSets(languageFilter?: CardLanguage | "ALL"): TcgSet[] {
  if (!languageFilter || languageFilter === "ALL") {
    return TCG_SETS;
  }
  return TCG_SETS.filter((s) => s.language === languageFilter);
}

/**
 * Finds a set by its code (e.g. "SV1S", "JTG", "SV2a", "MEW", "OBF") or alias.
 * If not in the static directory, dynamically recognizes the series and language
 * so NO valid official Pokémon set code will ever fail!
 */
export function findSetByCode(codeOrAlias: string): TcgSet | undefined {
  if (!codeOrAlias) return undefined;
  const target = codeOrAlias.trim().toLowerCase();

  // 1. Direct match in static registry
  const exact = TCG_SETS.find(
    (s) =>
      s.code.toLowerCase() === target ||
      s.id.toLowerCase() === target ||
      s.aliases.some((a) => a.toLowerCase() === target)
  );
  if (exact) return exact;

  const upper = codeOrAlias.trim().toUpperCase();

  // 2. Korean dynamic pattern (e.g. SV1S-KR, S6a-KR)
  if (target.endsWith("-kr") || target.endsWith("kr")) {
    const cleanCode = upper.replace(/-KR$/, "-KR");
    return {
      id: `${cleanCode.toLowerCase()}`,
      code: cleanCode,
      name: `${cleanCode} (Korean Edition)`,
      language: "KR",
      series: cleanCode.startsWith("SV") ? "Scarlet & Violet" : "Sword & Shield",
      releaseYear: 2024,
      totalCards: 100,
      aliases: [cleanCode, target],
    };
  }

  // 3. Chinese dynamic pattern (e.g. CS1, CSV1, AC1, AS5)
  if (/^(CS|CSV|AC|AS)\d+[A-Z]?$/i.test(target)) {
    return {
      id: `${target.toLowerCase()}-cn`,
      code: upper,
      name: `${upper} (Chinesische Ausgabe)`,
      language: "CN",
      series: upper.startsWith("CSV") ? "Scarlet & Violet CN" : "Sun & Moon CN",
      releaseYear: 2024,
      totalCards: 150,
      aliases: [upper, target],
    };
  }

  // 4. Japanese dynamic pattern: SV1S, SV1V, SV2a, S6a, S12a, SM12a, CP6, etc.
  if (/^(SV\d+[A-Za-z]?|S\d+[A-Za-z]?|SM\d+[A-Za-z]?|CP\d+)$/i.test(target)) {
    const series = upper.startsWith("SV")
      ? "Scarlet & Violet"
      : upper.startsWith("S")
      ? "Sword & Shield"
      : "Sun & Moon";
    return {
      id: `${target.toLowerCase()}-jp`,
      code: upper,
      name: `${upper} (Japanische Edition)`,
      language: "JP",
      series,
      releaseYear: 2024,
      totalCards: 100,
      aliases: [upper, target],
    };
  }

  // 5. Western 3-4 letter acronyms (e.g. SVI, PAL, OBF, MEW, PAR, PAF, TEF, TWM)
  if (/^[A-Za-z]{3,4}$/.test(target)) {
    return {
      id: `${target.toLowerCase()}-de`,
      code: upper,
      name: `${upper} (Western Set)`,
      language: "DE",
      series: "Pokémon TCG",
      releaseYear: 2024,
      totalCards: 180,
      aliases: [upper, target],
    };
  }

  return undefined;
}

/**
 * Detects the native language of a given set code or name.
 * e.g. "SV1S" -> "JP", "SV2a" -> "JP", "JTG" -> "DE"/"EN", "CS1" -> "CN", "SV1S-KR" -> "KR"
 */
export function detectSetLanguage(codeOrName: string): CardLanguage | null {
  if (!codeOrName) return null;
  const set = findSetByCode(codeOrName);
  if (set) return set.language;

  const lower = codeOrName.trim().toLowerCase();

  // Korean
  if (lower.endsWith("-kr") || lower.endsWith("kr") || /[\uAC00-\uD7AF]/.test(codeOrName)) {
    return "KR";
  }

  // Chinese
  if (
    lower.startsWith("cs") ||
    lower.startsWith("csv") ||
    lower.startsWith("ac") ||
    /[\u4E00-\u9FFF]/.test(codeOrName)
  ) {
    return "CN";
  }

  // Japanese
  if (
    /^(sv\d+[a-z]?|s\d+[a-z]?|sm\d+[a-z]?|cp\d+)$/i.test(lower) ||
    /[\u3040-\u309F\u30A0-\u30FF]/.test(codeOrName)
  ) {
    return "JP";
  }

  // Western
  return "DE";
}

/**
 * Cross-validates a set code against a chosen language as requested:
 * "Damit, wenn ich jetzt zum Beispiel oben auswähle, ich habe ein Glurak und ich gebe ein bei Set, das ist zum Beispiel jetzt Japanisch oder sagen wir mal Deutsch, JTG, also Journey Together, dann soll er mir direkt die Sprache der Karte halt auch so setzen. Genau andersrum, wenn ich sage, das ist eine deutsche Karte und ich gebe SV2A ein, dann soll er das Set halt nicht finden können."
 */
export function validateSetWithLanguage(
  setCodeOrName: string,
  selectedLanguage: CardLanguage
): {
  isValid: boolean;
  detectedLang: CardLanguage | null;
  matchedSet?: TcgSet;
  suggestedEquivalent?: TcgSet;
  warningMessage?: string;
} {
  if (!setCodeOrName) {
    return { isValid: true, detectedLang: null };
  }

  const matchedSet = findSetByCode(setCodeOrName);
  const detectedLang = matchedSet?.language || detectSetLanguage(setCodeOrName);

  if (!matchedSet) {
    return {
      isValid: false,
      detectedLang,
      warningMessage: `Set "${setCodeOrName}" ist im TCG-Index nicht verzeichnet.`,
    };
  }

  // Check language match
  // If user selected "DE" and types "SV2a" or "SV1S" (which is JP) -> Mismatch!
  const isLanguageMatch =
    matchedSet.language === selectedLanguage ||
    (selectedLanguage === "DE" && matchedSet.language === "EN") ||
    (selectedLanguage === "EN" && matchedSet.language === "DE") ||
    selectedLanguage === "Egal" ||
    selectedLanguage === "OTHER";

  if (!isLanguageMatch) {
    // Look for equivalent set in the user's selected language
    let suggestedEquivalent: TcgSet | undefined;
    if (matchedSet.equivalentCode) {
      suggestedEquivalent = TCG_SETS.find(
        (s) =>
          s.code.toLowerCase() === matchedSet.equivalentCode?.toLowerCase() &&
          s.language === selectedLanguage
      );
    }

    return {
      isValid: false,
      detectedLang,
      matchedSet,
      suggestedEquivalent,
      warningMessage: `Set "${matchedSet.code}" (${matchedSet.name}) ist ein ${
        matchedSet.language === "JP"
          ? "japanisches 🇯🇵"
          : matchedSet.language === "KR"
          ? "koreanisches 🇰🇷"
          : matchedSet.language === "CN"
          ? "chinesisches 🇨🇳"
          : matchedSet.language === "EN"
          ? "englisches 🇬🇧"
          : "deutsches 🇩🇪"
      } Set, deine Karte ist jedoch als "${selectedLanguage}" markiert.`,
    };
  }

  return {
    isValid: true,
    detectedLang,
    matchedSet,
  };
}
